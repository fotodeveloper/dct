"""Deterministic, offline rendering of the authored DCT workflow contracts.

Only the standard library is used. Rendering reads package sources; it never
imports integrations, discovers a home directory or touches a database.
"""
from __future__ import annotations

import json
import re
import tomllib
from pathlib import Path

MARKER = "Generated by scripts/render_skills.py from dct/skill_sources; DO NOT EDIT."
_NAME = re.compile(r"[a-z][a-z0-9-]*\Z")
_SLOT = re.compile(r"\{\{\s*([a-z]+)\.([a-z0-9_-]+)\s*\}\}")
_HOSTS = ("claude", "codex", "fallback")


def _root(root: Path | None) -> Path:
    return Path(root) if root is not None else Path(__file__).resolve().parent.parent


def load_manifest(root: Path | None = None) -> dict:
    """Return the validated inventory; invalid or path-escaping entries refuse."""
    base = _root(root)
    with (base / "dct/skill_sources/manifest.toml").open("rb") as handle:
        manifest = tomllib.load(handle)
    if set(manifest) != {"version", "hosts", "skills"} or manifest["version"] != 1:
        raise ValueError("Unsupported skill manifest schema")
    if set(manifest["hosts"]) != set(_HOSTS):
        raise ValueError("Manifest must define claude, codex and fallback hosts")
    for host, meta in manifest["hosts"].items():
        if set(meta) != {"display_name", "capabilities"} or not isinstance(meta["display_name"], str):
            raise ValueError(f"Invalid host metadata: {host}")
        if not isinstance(meta["capabilities"], list) or any(not isinstance(x, str) for x in meta["capabilities"]):
            raise ValueError(f"Invalid host capabilities: {host}")
    skills = manifest["skills"]
    if not isinstance(skills, list) or not skills:
        raise ValueError("Manifest needs at least one workflow")
    seen = set()
    for entry in skills:
        if set(entry) != {"name", "description", "short_description", "explicit_only", "body", "entry_tool"}:
            raise ValueError("Unknown or missing workflow metadata")
        name = entry["name"]
        if not isinstance(name, str) or not _NAME.fullmatch(name) or name in seen:
            raise ValueError(f"Invalid or duplicate workflow name: {name!r}")
        seen.add(name)
        if entry["body"] != f"workflows/{name}.md":
            raise ValueError(f"Workflow body must use its fixed source path: {name}")
        description = entry["description"]
        if not isinstance(description, str) or not description.strip() or "\n" in description or "\r" in description:
            raise ValueError(f"Description must be a nonempty single line: {name}")
        short = entry["short_description"]
        if not isinstance(short, str) or not 25 <= len(short) <= 64 or any(char in short for char in "\n\r"):
            raise ValueError(f"short_description must be a single line of 25–64 characters: {name}")
        if not isinstance(entry["entry_tool"], str) or not entry["entry_tool"].strip() or any(char in entry["entry_tool"] for char in "\n\r"):
            raise ValueError(f"entry_tool must be a nonempty single line: {name}")
        if type(entry["explicit_only"]) is not bool:
            raise ValueError(f"explicit_only must be boolean: {name}")
    return manifest


def skill_names(root: Path | None = None) -> tuple[str, ...]:
    """Canonical workflow names in manifest order, shared by both adapters."""
    return tuple(entry["name"] for entry in load_manifest(root)["skills"])


def _read(sources: Path, relative: str) -> str:
    path = sources / relative
    if not path.resolve().is_relative_to(sources.resolve()):
        raise ValueError(f"Source leaves skill_sources: {relative}")
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise ValueError(f"Missing source fragment: {relative}") from exc


def _expand(text: str, sources: Path, host: str, stack: tuple[str, ...] = ()) -> str:
    def replace(match: re.Match) -> str:
        namespace, name = match.groups()
        if namespace == "host":
            relative = f"hosts/{host}/{name}.md"
        elif namespace == "shared":
            relative = f"shared/{name}.md"
        else:
            raise ValueError(f"Unknown source slot: {match.group(0)}")
        if relative in stack:
            raise ValueError(f"Cyclic source fragments: {' -> '.join((*stack, relative))}")
        return _expand(_read(sources, relative), sources, host, (*stack, relative)).rstrip()
    rendered = _SLOT.sub(replace, text)
    if "{{" in rendered:
        raise ValueError("Unknown or malformed source slot")
    return rendered


def validate_frontmatter(text: str, *, name: str, description: str, explicit_only: bool, host: str) -> None:
    """Parse the deliberately bounded YAML frontmatter emitted by the renderer.

    JSON-quoted strings are YAML double-quoted scalars. Restricting the grammar
    gives a real parse/round-trip check without adding a YAML dependency.
    """
    lines = text.splitlines()
    if not lines or lines[0] != "---":
        raise ValueError("SKILL.md must begin with YAML frontmatter")
    try:
        end = lines.index("---", 1)
    except ValueError as exc:
        raise ValueError("Unterminated SKILL.md frontmatter") from exc
    fields = {}
    for line in lines[1:end]:
        key, separator, value = line.partition(": ")
        if not separator or key in fields:
            raise ValueError("Invalid or duplicate YAML frontmatter field")
        try:
            fields[key] = json.loads(value)
        except json.JSONDecodeError as exc:
            raise ValueError("Invalid YAML frontmatter scalar") from exc
    expected = {"name": name, "description": description}
    if host == "claude" and explicit_only:
        expected["disable-model-invocation"] = True
    if fields != expected:
        raise ValueError(f"Wrong-host or inconsistent SKILL.md metadata: {name}")


def _skill(entry: dict, body: str, host: str) -> str:
    front = "---\n" + "\n".join(f"{key}: {json.dumps(entry[key], ensure_ascii=False)}" for key in ("name", "description")) + "\n"
    if host == "claude" and entry["explicit_only"]:
        front += "disable-model-invocation: true\n"
    result = front + f"---\n<!-- {MARKER} -->\n\n" + body.strip() + "\n"
    validate_frontmatter(result, name=entry["name"], description=entry["description"], explicit_only=entry["explicit_only"], host=host)
    return result


def _fallback_headings(text: str) -> str:
    """Nest a standalone workflow under its fallback heading, preserving code."""
    result = []
    fence = None
    for line in text.splitlines():
        # Authored workflows use standalone and list-container fences. Keep
        # their indentation context, so deeper literal fences cannot close one.
        opening = re.match(r"^([ \t]*)(?:(?:[-+*]|[0-9]+[.)])[ \t]+)?(`{3,}|~{3,})", line)
        if fence is not None:
            result.append(line)
            closing = re.fullmatch(r"([ \t]*)(" + re.escape(fence[0]) + r"{" + str(fence[1]) + r",})[ \t]*", line)
            if closing and fence[2] <= len(closing.group(1).expandtabs(4)) <= fence[2] + 3:
                fence = None
        elif opening:
            prefix = line[:opening.start(2)]
            indentation = len(opening.group(1).expandtabs(4))
            container = len(prefix.expandtabs(4)) if prefix.strip() else (0 if indentation <= 3 else indentation)
            fence = (opening.group(2)[0], len(opening.group(2)), container)
            result.append(line)
        else:
            heading = re.match(r"^(#{1,6})([ \t]+.*)$", line)
            result.append("#" * min(6, len(heading.group(1)) + 2) + heading.group(2) if heading else line)
    return "\n".join(result)


def render_all(root: Path | None = None) -> dict[str, str]:
    """Render every fixed output path in memory; missing/unknown inputs fail."""
    base = _root(root)
    sources = base / "dct/skill_sources"
    manifest = load_manifest(base)
    outputs = {}
    fallback = []
    for entry in manifest["skills"]:
        name = entry["name"]
        body = _read(sources, entry["body"])
        for host in _HOSTS:
            rendered = _expand(body, sources, host, (entry["body"],))
            if host == "fallback":
                fallback.append(f"## `/{name}` fallback\n\n{_fallback_headings(rendered.strip())}\n")
            else:
                target = f"dct/skills/{name}/SKILL.md" if host == "claude" else f"dct/assets/codex-{name}.md"
                outputs[target] = _skill(entry, rendered, host)
        outputs[f"dct/assets/codex-{name}.yaml"] = (
            f"# {MARKER}\ninterface:\n"
            f"  display_name: {json.dumps(name)}\n"
            f"  short_description: {json.dumps(entry['short_description'], ensure_ascii=False)}\n"
            f"policy:\n  allow_implicit_invocation: {str(not entry['explicit_only']).lower()}\n"
        )
    workflows = "\n".join(fallback)
    inventory = "\n".join(f"- `{entry['name']}` — {entry['description']} Entry: `{entry['entry_tool']}`. Explicit only: {str(entry['explicit_only']).lower()}." for entry in manifest["skills"])
    reference = _read(sources, "shared/reference.md")
    if "{{inventory}}" not in reference:
        raise ValueError("Reference must include the canonical workflow inventory")
    reference = reference.replace("{{workflows}}", workflows).replace("{{inventory}}", inventory)
    outputs["dct/assets/dct-reference.md"] = f"<!-- {MARKER} -->\n\n" + _expand(reference, sources, "fallback").strip() + "\n"
    header = _expand(_read(sources, "hosts/fallback/header.md"), sources, "fallback")
    footer = _expand(_read(sources, "hosts/fallback/footer.md"), sources, "fallback")
    outputs["docs/assistant-fallbacks.md"] = f"<!-- {MARKER} -->\n\n{header.strip()}\n\n{workflows}\n{footer.strip()}\n"
    return outputs


def freshness_errors(root: Path | None = None) -> list[str]:
    """Report missing/stale/unexpected generated artifacts without writing."""
    base = _root(root)
    expected = render_all(base)
    errors = []
    for relative, text in expected.items():
        path = base / relative
        if not path.is_file():
            errors.append(f"missing: {relative}")
        elif path.read_bytes() != text.encode("utf-8"):
            errors.append(f"stale: {relative}")
    candidates = set((base / "dct/skills").glob("*/SKILL.md"))
    candidates.update((base / "dct/assets").glob("codex-*.yaml"))
    # codex-agents.md is a bounded installation block, not a workflow.
    candidates.update(p for p in (base / "dct/assets").glob("codex-*.md") if p.name != "codex-agents.md")
    for path in sorted(candidates):
        relative = path.relative_to(base).as_posix()
        if relative not in expected:
            errors.append(f"unexpected: {relative}")
    return errors


def check_freshness(root: Path | None = None) -> None:
    """Refuse stale builds; callers must regenerate explicitly beforehand."""
    errors = freshness_errors(root)
    if errors:
        raise ValueError("Generated workflow outputs are not fresh; run python scripts/render_skills.py:\n" + "\n".join(errors))
