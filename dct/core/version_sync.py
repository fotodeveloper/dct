"""The version-sync script a project's release runs (K-76, dogfood of #877).

dct's release runs `scripts/dct-version-sync.sh <version>` (else
`scripts/version-sync.sh`) once, in an isolated checkout of the commit being
released, before the owner approves the release (workflows/release/effects.py).
This module writes that script for a project from the packaged generic
template (dct/assets/dct-version-sync.sh, every block commented) with the
block of the project's version file switched on. It never overwrites an
existing script — the owner's own script stays the owner's.
"""

from __future__ import annotations

from pathlib import Path

from dct.assets import version_sync_template_path
from dct.core.version import VERSION_FILES

SCRIPT_PATH = "scripts/dct-version-sync.sh"
# Line 2 of the template, after the shebang: /dct-init recognises a script it
# generated by it.
SENTINEL = "# dct-version-sync template v1"


def render(kind: str) -> str:
    """The template with the block of `kind` (a VERSION_FILES entry) switched
    on: the "# " prefix of every line between `# >>> kind` and `# <<< kind`
    removed. Raises ValueError for an unknown kind or a template without a
    well-formed block for it."""
    if kind not in VERSION_FILES:
        raise ValueError(f"no version-sync block for {kind!r} — one of: {', '.join(VERSION_FILES)}")
    lines = version_sync_template_path().read_text(encoding="utf-8").splitlines(keepends=True)
    try:
        start, end = lines.index(f"# >>> {kind}\n"), lines.index(f"# <<< {kind}\n")
    except ValueError:
        raise ValueError(f"the version-sync template has no block for {kind}") from None
    if end <= start + 1:
        raise ValueError(f"the version-sync block for {kind} is empty")
    for n in range(start + 1, end):
        if not lines[n].startswith("# "):
            raise ValueError(f"line {n + 1} of the {kind} block is not commented")
        lines[n] = lines[n][2:]
    return "".join(lines)


def write_script(project_root: str | Path, kind: str) -> dict:
    """Write SCRIPT_PATH under `project_root` with the block of `kind`
    switched on, executable. Exclusive create: raises FileExistsError when
    anything — a file, a directory or a (dangling) symlink — already has that
    name, so nothing is ever overwritten or written through a link. Raises
    ValueError for an unknown kind. Returns {"path", "kind"}."""
    content = render(kind)
    target = Path(project_root) / SCRIPT_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    with open(target, "x", encoding="utf-8") as fh:
        fh.write(content)
    target.chmod(0o755)
    return {"path": SCRIPT_PATH, "kind": kind}
